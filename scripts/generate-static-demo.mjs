/**
 * Generates static demo data for GitHub Pages demo mode.
 * Run after building @memorium/core and @memorium/demo.
 */
import { writeFile, mkdir, cp } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { createDemoItems, demoSubjectName } from "../packages/demo/dist/index.js";
import { IMPORT_SOURCES } from "../packages/ingest/dist/import-sources.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assetDir = join(root, "packages/demo/assets");
const jsonOutDir = process.env.DEMO_OUT_DIR
  ? resolve(process.env.DEMO_OUT_DIR)
  : join(root, "apps/web/public/demo");
const mediaOutDir = process.env.DEMO_OUT_DIR
  ? join(resolve(process.env.DEMO_OUT_DIR), "media")
  : join(root, "apps/web/public/demo/media");
const tsOutFile = process.env.DEMO_TS_OUT
  ? resolve(process.env.DEMO_TS_OUT)
  : join(root, "apps/web/src/generated/demo-data.ts");

const memorialId = "00000000-0000-4000-8000-000000000001";
const memorial = {
  id: memorialId,
  name: demoSubjectName(),
  description: "Mother, gardener, and keeper of Sunday recipes. Every memory here is preserved with love.",
  createdAt: "2026-01-01T00:00:00.000Z",
  bornAt: "1945-03-12T00:00:00.000Z",
  diedAt: "2022-11-08T00:00:00.000Z",
  tribute: "Mother, gardener, and keeper of Sunday recipes.",
  portraitPath: "demo/media/portrait.svg",
};

const items = createDemoItems(memorialId);

const timeline = Object.entries(
  items.reduce((acc, item) => {
    const period = item.occurredAt.slice(0, 7);
    acc[period] = (acc[period] ?? 0) + 1;
    return acc;
  }, {}),
)
  .map(([period, count]) => ({ period, count }))
  .sort((a, b) => a.period.localeCompare(b.period));

const stats = { total: items.length };
for (const item of items) {
  stats[`type:${item.type}`] = (stats[`type:${item.type}`] ?? 0) + 1;
  stats[`source:${item.source}`] = (stats[`source:${item.source}`] ?? 0) + 1;
}

const searchResult = { items, total: items.length };

await mkdir(dirname(tsOutFile), { recursive: true });
await mkdir(jsonOutDir, { recursive: true });
await mkdir(mediaOutDir, { recursive: true });
await cp(assetDir, mediaOutDir, { recursive: true });

const tsSource = `// Auto-generated by scripts/generate-static-demo.mjs — do not edit
import type { ImportSource, Memorial, MemoryItem, TimelinePeriod } from "../api";

export const demoMemorial = ${JSON.stringify(memorial, null, 2)} as Memorial;

export const demoItems = ${JSON.stringify(items, null, 2)} as MemoryItem[];

export const demoTimeline = ${JSON.stringify(timeline, null, 2)} as TimelinePeriod[];

export const demoStats = ${JSON.stringify(stats, null, 2)} as Record<string, number>;

export const demoImportSources = ${JSON.stringify(IMPORT_SOURCES, null, 2)} as ImportSource[];
`;

await Promise.all([
  writeFile(tsOutFile, tsSource),
  writeFile(join(jsonOutDir, "memorial.json"), JSON.stringify(memorial, null, 2)),
  writeFile(join(jsonOutDir, "items.json"), JSON.stringify(searchResult, null, 2)),
  writeFile(join(jsonOutDir, "timeline.json"), JSON.stringify(timeline, null, 2)),
  writeFile(join(jsonOutDir, "stats.json"), JSON.stringify(stats, null, 2)),
  writeFile(join(jsonOutDir, "import-sources.json"), JSON.stringify(IMPORT_SOURCES, null, 2)),
]);

console.log(`✓ Generated static demo data (${items.length} items)`);
console.log(`  TypeScript: ${tsOutFile}`);
console.log(`  Media assets: ${mediaOutDir}`);
